import { buildPremiumHtmlPreview } from './premiumPreview.js'
import { parseMarkdownSlides } from './presentationParser.js'
import { buildSlideHtml } from './classicSlideRenderer.js'
import { PREVIEW_CSS } from './classicPreviewStyles.js'

export function buildClassicHtmlPreview(markdown) {
  const slides = parseMarkdownSlides(markdown)
  if (!slides.length) return ''

  const total = slides.length
  const slideHtml = slides.map((slide, i) => buildSlideHtml(slide, i, total)).join('')

  return `<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<style>${PREVIEW_CSS}</style>
</head>
<body>${slideHtml}</body>
</html>`
}

export function buildHtmlPreview(markdown) {
  return buildPremiumHtmlPreview(markdown, { responsive: true })
}


